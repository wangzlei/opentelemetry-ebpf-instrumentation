#!/usr/bin/env bash
# Copy the patched OBI tree and the obi receiver INTO a cwagent checkout, so that
# branch builds on its own (no ../adot-obi replace). One-way: OBI is still developed
# here (patches/), this only refreshes the cwagent branch's copies.
#
#   scripts/vendor-into-cwagent.sh <cwagent dir>
#
# Needs a current build/obi (scripts/apply-patches.sh). The generated BPF bindings are NOT
# copied: the cwagent branch generates them at build time (make ebpf-generate).
# Writes, replacing whatever is there:
#   <cwagent>/third_party/obi        tracked files of build/obi (obi-snapshot.exclude,
#                                    minus examples/, devdocs/, AGENTS.md, CLAUDE.md; plus
#                                    the promtest package)
#   <cwagent>/receiver/obireceiver   receiver/obireceiver as a package of cwagent's
#                                    main module (no go.mod/go.sum, cwagent import path)
#   <cwagent>/third_party/obi/ADOT_OBI_SOURCE   which adot-obi commit and patches it came from
# Then commit the result in the cwagent branch.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
CW=$(cd "${1:?cwagent dir}" && pwd); SRC="$ROOT/build/obi"
[[ -f $CW/go.mod ]] && grep -q '^module github.com/aws/amazon-cloudwatch-agent$' "$CW/go.mod" || { echo "$CW is not a cwagent checkout"; exit 1; }
[[ -d $SRC/.git ]] || { echo "$SRC is not a patched tree: run scripts/apply-patches.sh"; exit 1; }

list=$(mktemp); trap 'rm -f "$list"' EXIT
{ git -C "$SRC" ls-files | grep -v -E -f "$ROOT/scripts/obi-snapshot.exclude" | grep -v -E '^(examples|devdocs)/|^(AGENTS|CLAUDE)\.md$'
  # the one integration-test package that OBI unit tests import (needed by go mod tidy)
  git -C "$SRC" ls-files internal/test/integration/components/promtest; } | sort -u > "$list"
rm -rf "$CW/third_party/obi"; mkdir -p "$CW/third_party/obi"
rsync -a --files-from="$list" "$SRC/" "$CW/third_party/obi/"
cat > "$CW/third_party/obi/ADOT_OBI_SOURCE" <<EOF
Generated by adot-obi scripts/vendor-into-cwagent.sh: do not edit, change adot-obi and re-run.
upstream OBI:  $(git -C "$ROOT/upstream" describe --tags 2>/dev/null || git -C "$ROOT/upstream" rev-parse --short HEAD)
adot-obi:      $(git -C "$ROOT" log -1 --format=%h --abbrev=8 -- patches receiver) (last commit changing patches/ or receiver/)$(git -C "$ROOT" diff --quiet HEAD -- patches receiver || echo ', working tree differs')
patched tree:  $(git -C "$SRC" log -1 --format='%h %s')
patches:       $(cd "$ROOT/patches" && ls *.patch | tr '\n' ' ')
EOF

D="$CW/receiver/obireceiver"; rm -rf "$D"; mkdir -p "$D"
for f in "$ROOT"/receiver/obireceiver/*.go; do
  sed 's#// import "github.com/aws-observability/adot-obi/receiver/obireceiver"#// import "github.com/aws/amazon-cloudwatch-agent/receiver/obireceiver"#' "$f" > "$D/$(basename "$f")"
done
echo "third_party/obi: $(wc -l < "$list" | tr -d ' ') files, $(du -sh "$CW/third_party/obi" | cut -f1)"
echo "receiver/obireceiver: $(ls "$D" | wc -l | tr -d ' ') files"
